# Operadores de comparacion
# Operador igual
d = 4
b = 2
resultado = d == b # Comprobamos si son ioguales
print(resultado)

# Operador distinto
resultado = d != b
print(resultado)

# Operador mayor que
resultado = d > b
print(resultado)

# Operador menor que
resultado = d < b
print(resultado)

# Operador menor o igual que
resultado = d <= b
print(resultado)

# Operador nayor o igual que
resultado = d >= b
print(resultado)